"""Clean the chunk JSON produced by backend/scripts/02_legal_chunker.py.

The chunker output has a few known problems (found by auditing the file). This module
fixes the ones that can be fixed safely and FLAGS the rest, so nothing is silently
changed and nothing invented is shown as statute text:

* every section body ends with the NEXT section's heading (headings come before the
  section number in the source page)            -> removed, flag trailing_next_title_removed
* the chunker gives the last section of every chapter the NEXT chapter's name and leaves that
  chapter's subtitle at the end of its text -> chapter corrected, subtitle removed,
                                                     flag chapter_boundary_fixed
* some chapters are really section text           -> replaced by the previous valid chapter,
                                                     flag chapter_inferred
* some titles are only a footnote number (e.g. '92'); the real heading is the line
  just before that number at the end of the previous section -> recovered, flag title_recovered
  (if that pattern is not found: flag title_missing)
* section number repeated (a sub-clause such as
  '৭।' was taken for a section)                   -> later copy not indexed, flag duplicate_section_number
* repealed placeholders (184, 253-262) whose text
  was generated by the script, not copied from
  the Act                                         -> not indexed, flag placeholder_generated_text
"""
import re
import unicodedata

_BN = "০১২৩৪৫৬৭৮৯"
_TO_ASCII = str.maketrans(_BN, "0123456789")
_TO_BN = str.maketrans("0123456789", _BN)

PLACEHOLDER_TEXT = (
    "(এই ধারার মূল টেক্সট সংগ্রহ করা হয়নি; ধারাটি বিলুপ্ত হিসেবে চিহ্নিত। "
    "সর্বশেষ পাঠের জন্য bdlaws.minlaw.gov.bd দেখুন।)"
)
MISSING_TITLE = "(শিরোনাম পাওয়া যায়নি)"
LONG_TEXT_CHARS = 8000

def _nfc(text: str) -> str:
    """Bangla letters such as 'য়' exist in two encodings; compare them in one form."""
    return unicodedata.normalize("NFC", text)


_PLACEHOLDER_CHAPTER_STARTS = (_nfc("অপ্রযোজ্য"), _nfc("পঞ্চদশ অধ্যায় (বিলুপ্ত)"))
_CHAPTER_OK = re.compile(_nfc(r"^[^\d০-৯()\[\]]{2,30}?অধ্যায়\s*\("))
_ONLY_DIGITS = re.compile(r"^[\d০-৯\s]+$")


def to_ascii_digits(text: str) -> str:
    return text.translate(_TO_ASCII)


def to_bangla_digits(text: str) -> str:
    return text.translate(_TO_BN)


def normalise_section_number(value: str) -> str:
    """'108', ' ১০৮ ' -> '১০৮' (the form stored in the database)."""
    return to_bangla_digits(value.strip().replace(" ", ""))


def base_number(section_number: str) -> int | None:
    m = re.match(r"^(\d+)", to_ascii_digits(section_number))
    return int(m.group(1)) if m else None


def is_placeholder(chunk: dict) -> bool:
    chapter = _nfc(chunk.get("chapter", "")).lstrip("[ ")
    return chapter.startswith(_PLACEHOLDER_CHAPTER_STARTS)


def is_valid_chapter(chapter: str) -> bool:
    return bool(_CHAPTER_OK.match(_nfc(chapter).lstrip("[ ").strip()))


def clean_chunks(chunks: list[dict]) -> tuple[list[dict], dict]:
    """Return (cleaned records, report). Order is preserved; no record is dropped."""
    real = [c for c in chunks if not is_placeholder(c)]
    next_title = {
        id(real[i]): real[i + 1].get("section_title", "").strip()
        for i in range(len(real) - 1)
    }

    recovered_titles: dict[int, str] = {}
    records: list[dict] = []
    seen: set[str] = set()
    last_chapter = "অজানা অধ্যায়"
    counts = {
        "trailing_next_title_removed": 0,
        "chapter_boundary_fixed": 0,
        "chapter_inferred": 0,
        "title_recovered": 0,
        "title_missing": 0,
        "duplicate_section_number": 0,
        "placeholder_generated_text": 0,
        "very_long_text": 0,
    }

    for chunk in chunks:
        number = chunk["section_number"].strip()
        flags: list[str] = []
        title = chunk.get("section_title", "").strip()
        chapter = chunk.get("chapter", "").strip()
        text = chunk.get("raw_body", "").strip()
        indexed = True

        if is_placeholder(chunk):
            flags.append("placeholder_generated_text")
            text = PLACEHOLDER_TEXT
            indexed = False
            title = MISSING_TITLE if _ONLY_DIGITS.match(title or "0") else title
        else:
            if is_valid_chapter(chapter):
                last_chapter = chapter.lstrip("[ ").strip()
                chapter = last_chapter
            else:
                chapter = last_chapter
                flags.append("chapter_inferred")

            nxt = next_title.get(id(chunk))
            lines = text.splitlines()
            if nxt and len(lines) > 1 and lines[-1].strip() == nxt:
                if _ONLY_DIGITS.match(nxt) and len(lines) > 2 and len(lines[-2].strip()) <= 120:
                    # ... real heading, footnote number  -> both belong to the next section
                    recovered_titles[id(real[real.index(chunk) + 1])] = lines[-2].strip()
                    text = "\n".join(lines[:-2]).strip()
                else:
                    text = "\n".join(lines[:-1]).strip()
                flags.append("trailing_next_title_removed")

            if not title or _ONLY_DIGITS.match(title):
                if id(chunk) in recovered_titles:
                    title = recovered_titles[id(chunk)]
                    flags.append("title_recovered")
                else:
                    title = MISSING_TITLE
                    flags.append("title_missing")

            if len(text) > LONG_TEXT_CHARS:
                flags.append("very_long_text")

        if number in seen and not is_placeholder(chunk):
            flags.append("duplicate_section_number")
            indexed = False
        seen.add(number)

        for f in flags:
            counts[f] += 1

        records.append(
            {
                "source_chunk_id": chunk.get("id", f"sec_{number}"),
                "section_number": number,
                "title": title,
                "chapter": chapter,
                "text": text,
                "legal_status": chunk.get("legal_status"),
                "amendment_note": chunk.get("amendment_provenance"),
                "flags": flags,
                "is_indexed": indexed,
            }
        )

    # Last section of a chapter: the chunker read the NEXT chapter heading before saving it, so
    # it carries the next chapter's name and ends with that chapter's subtitle, e.g.
    # 'প্রসূতি কল্যাণ সুবিধা' for 'চতুর্থ অধ্যায় (প্রসূতি কল্যাণ সুবিধা)'.
    searchable = [r for r in records if "placeholder_generated_text" not in r["flags"]]
    for prev, cur in zip(searchable, searchable[1:]):
        if cur["chapter"] == prev["chapter"]:
            continue
        lines = cur["text"].splitlines()
        last = lines[-1].strip() if lines else ""
        if len(lines) > 1 and last and f"({_nfc(last)})" in _nfc(cur["chapter"]):
            cur["text"] = "\n".join(lines[:-1]).strip()
            cur["chapter"] = prev["chapter"]
            cur["flags"].append("chapter_boundary_fixed")
            counts["chapter_boundary_fixed"] += 1

    bases = {base_number(r["section_number"]) for r in records}
    bases.discard(None)
    real_bases = [
        base_number(r["section_number"])
        for r in records
        if "placeholder_generated_text" not in r["flags"]
        and "duplicate_section_number" not in r["flags"]
    ]
    top = max(real_bases) if real_bases else 0
    missing = [n for n in range(1, top + 1) if n not in bases]

    report = {
        "total_records": len(records),
        "indexed_records": sum(1 for r in records if r["is_indexed"]),
        "not_indexed_records": sum(1 for r in records if not r["is_indexed"]),
        "flag_counts": counts,
        "section_numbers_missing_from_source_parse": [to_bangla_digits(str(n)) for n in missing],
        "warnings": [
            "legal_status / amendment_note come from the chunker and are NOT verified: "
            "the chunker matches 'ধারা 1' inside 'ধারা 184' etc. They are stored but not shown to users.",
        ],
    }
    return records, report
